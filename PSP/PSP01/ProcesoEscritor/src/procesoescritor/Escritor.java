package procesoescritor;

/**
 *
 * @author 1yk0s
 */
public class Escritor {
    
    public static void main(String[] args) {
        /*
            Lo único que se hace es escribir los números del 0 al 9
            en la salida estándar del proceso.
        */
        for (int i = 0; i < 10; i++) {
            System.out.println(i);
        }
    }
    
    /*
        Se está escribiendo en la salida estándar del proceso de los números
        del 0 al 9.
    */
}
